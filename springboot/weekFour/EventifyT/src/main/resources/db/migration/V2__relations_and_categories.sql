-- V2: evolucion relacional
--   * venues.city (obligatoria)
--   * events.active (soft delete) y events.venue_id (Many-to-One obligatoria)
--   * categories + tabla intermedia events_categories (Many-to-Many)

-- Ciudad: el DEFAULT solo sirve para rellenar filas que ya existieran; luego se quita
ALTER TABLE venues ADD COLUMN city VARCHAR(100) NOT NULL DEFAULT 'Sin ciudad';
ALTER TABLE venues ALTER COLUMN city DROP DEFAULT;

-- Soft delete: todo evento nace activo
ALTER TABLE events ADD COLUMN active BOOLEAN NOT NULL DEFAULT TRUE;

-- Relacion obligatoria evento -> lugar
ALTER TABLE events ADD COLUMN venue_id BIGINT NOT NULL;
ALTER TABLE events
    ADD CONSTRAINT fk_events_venue FOREIGN KEY (venue_id) REFERENCES venues (id);

CREATE TABLE categories
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255)
);

-- Tabla intermedia con nombres explicitos (event_id, category_id)
CREATE TABLE events_categories
(
    event_id    BIGINT NOT NULL REFERENCES events (id),
    category_id BIGINT NOT NULL REFERENCES categories (id),
    PRIMARY KEY (event_id, category_id)
);

-- Indices para los filtros y el orden del catalogo
CREATE INDEX idx_events_date ON events (date DESC);
CREATE INDEX idx_events_venue_id ON events (venue_id);
CREATE INDEX idx_venues_city ON venues (city);
CREATE INDEX idx_events_categories_category ON events_categories (category_id);
